// Builds `src/components/ui/solar-icons.ts` from the icons actually referenced in `src/`.
//
// Why: `@iconify/react` normally fetches icon data from api.iconify.design at runtime, and the
// app's CSP blocks that (connect-src only allows self, Supabase, Turnstile, the local API), so
// icons silently disappeared. Bundling the used subset keeps rendering offline and avoids
// shipping the whole Solar set to the browser.
//
// Usage: `npm run icons` (rerun whenever a new `solar:*` icon is added).

import { readFileSync, writeFileSync, readdirSync, statSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outputPath = join(root, "src", "components", "ui", "solar-icons.ts");
const collectionPath = join(root, "node_modules", "@iconify-json", "solar", "icons.json");

const sources = [];
const walk = (dir) => {
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) walk(full);
    else if (/\.(ts|tsx)$/.test(entry)) sources.push(full);
  }
};
walk(join(root, "src"));

const used = new Set();
for (const file of sources) {
  if (file === outputPath) continue;
  const text = readFileSync(file, "utf8");
  for (const match of text.matchAll(/solar:[a-z0-9-]+/g)) used.add(match[0].slice("solar:".length));
}
if (used.size === 0) throw new Error("No solar:* icons referenced in src/");

const collection = JSON.parse(readFileSync(collectionPath, "utf8"));

const resolveIcon = (name, seen = new Set()) => {
  const icon = collection.icons?.[name];
  if (icon) return icon;
  const alias = collection.aliases?.[name];
  if (!alias || seen.has(name)) return null;
  seen.add(name);
  return alias.parent ? resolveIcon(alias.parent, seen) : alias;
};

const icons = {};
const missing = [];
for (const name of [...used].sort()) {
  const data = resolveIcon(name);
  if (data) icons[name] = data;
  else missing.push(name);
}
if (missing.length) throw new Error(`Unknown solar icons: ${missing.join(", ")}`);

const payload = { prefix: "solar", width: collection.width, height: collection.height, icons };
writeFileSync(outputPath, `// Generated by scripts/build-solar-icons.mjs — run \`npm run icons\` after adding icons.
// Keep this file out of hand edits: the icon list follows the \`solar:*\` references in src/.
import type { IconifyJSON } from "@iconify/react/offline";

export const solarIcons: IconifyJSON = ${JSON.stringify(payload, null, 2)};
`);

console.log(`Wrote ${Object.keys(icons).length} solar icons from ${sources.length} source files.`);
